/** Действующая ставка продукта — последняя незамещённая запись. */
export function currentRate(productId: string): RateRecord | undefined {
  return RATE_RECORDS.filter((r) => r.productId === productId && r.supersededAt === undefined).sort(
    (a, b) => b.verifiedAt.localeCompare(a.verifiedAt),
  )[0];
}

export function productById(id: string): DepositProduct | undefined {
  return DEPOSIT_PRODUCTS.find((p) => p.id === id);
}
